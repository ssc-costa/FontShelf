import { test, expect } from '@playwright/test';

test('multiline phrases, styling, restart and comparison stay in sync', async ({ page }, testInfo) => {
  const errors: string[] = [];
  page.on('pageerror', (e) => errors.push(e.message));
  await page.route('http://asset.localhost/**', (route) => route.abort());
  await page.goto('/tests/ui/harness.html');
  await expect(page.locator('.preview-text')).toHaveCount(2);
  const text = '  Café & Bar\n¡Abierto! €12,50 — 99%  ';
  await page.getByLabel('Your sample text', { exact: true }).fill(text);
  await page.getByLabel('Phrase name', { exact: true }).fill('Signage');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await page.getByLabel('Letter spacing', { exact: true }).fill('0.1');
  await page.getByLabel('Line height', { exact: true }).fill('1.8');
  await page.getByLabel('Ink', { exact: true }).fill('#ffcc88');
  await page.getByLabel('Paper', { exact: true }).fill('#222222');
  await expect(page.locator('.preview-text').first()).toHaveJSProperty('textContent', text);
  await expect(page.locator('.preview-text').first()).toHaveCSS('white-space', 'pre-wrap');
  await expect(page.locator('.preview-text').first()).toHaveCSS('color', 'rgb(255, 204, 136)');
  await expect(page.locator('.preview-text').first()).toHaveCSS('letter-spacing', '3.2px');
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('ui-test-prefs') ?? '{}').previewOptions?.tracking)).toBe(0.1);
  await page.reload();
  await expect(page.getByLabel('Your sample text', { exact: true })).toHaveValue(text);
  await page.getByLabel('Your sample text', { exact: true }).fill('Different');
  await page.getByLabel('Saved phrases', { exact: true }).selectOption({ label: 'Signage' });
  await expect(page.getByLabel('Your sample text', { exact: true })).toHaveValue(text);
  await page.locator('.family-card').nth(0).click();
  await page.locator('.family-card').nth(1).click({ modifiers: ['Control'] });
  await page.getByRole('button', { name: /Compare.*2|Compare 2/ }).click();
  const dialog = page.getByRole('dialog');
  await expect(dialog).toBeVisible();
  await dialog.getByLabel('Your sample text', { exact: true }).fill('Compare me\nAcross both fonts');
  await expect(dialog.locator('.compare-line')).toHaveCount(6);
  await expect(dialog.locator('.compare-line').first()).toHaveJSProperty('textContent', 'Compare me\nAcross both fonts');
  await page.screenshot({ path: testInfo.outputPath('comparison.png') });
  await dialog.getByRole('button', { name: 'Close comparison', exact: true }).click();
  await expect(page.getByLabel('Your sample text', { exact: true })).toHaveValue('Compare me\nAcross both fonts');
  await page.getByRole('button', { name: 'Reset preview styling', exact: true }).click();
  await page.getByLabel('Your sample text', { exact: true }).fill('FontShelf\nFind the right type.');
  await page.screenshot({ path: testInfo.outputPath('library.png') });
  await page.setViewportSize({ width: 1000, height: 700 });
  await page.screenshot({ path: testInfo.outputPath('small-desktop.png') });
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false);
  expect(errors).toEqual([]);
});
